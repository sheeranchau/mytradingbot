"""
Unified data models shared across all components.
"""
import time
from dataclasses import dataclass, field, asdict
from typing import Optional


class OrderState:
    """Order lifecycle states (normalised across all gateways)."""
    PENDING_SUBMIT = "pending_submit"  # Created locally, not yet ACKed by exchange
    OPEN           = "open"            # Resting in the exchange book
    PARTIAL        = "partial"         # Partially filled, still open
    FILLED         = "filled"          # Fully filled
    CANCELLED      = "cancelled"       # Cancelled (may carry partial fills)
    REJECTED       = "rejected"        # Rejected by exchange or risk
    EXPIRED        = "expired"         # Expired (IOC/FOK/GTD)

    TERMINAL = frozenset({FILLED, CANCELLED, REJECTED, EXPIRED})


@dataclass
class OrderUpdate:
    """
    Unified order lifecycle + fill event model.

    One instance covers the full lifecycle: from local creation through exchange
    acknowledgement, incremental fills, and terminal states.

    When ``fill_id`` is non-empty this update also carries a fill event (the
    per-fill fields are populated).  An update without a fill_id is a pure
    state change (e.g. cancel confirmation, open acknowledgement).
    """

    # ── Identity ──────────────────────────────────────────────────────────
    client_order_id: str = ""   # clOrdId — generated by us, sent to exchange
    order_id: str       = ""    # ordId   — assigned by exchange after submission
    gateway: str        = ""    # "okx" | "futu" | "webull"
    strategy: str       = ""    # strategy name; "" for manual/dashboard orders

    # ── Instrument ────────────────────────────────────────────────────────
    symbol: str = ""

    # ── Order params (immutable after submission) ─────────────────────────
    side: str       = ""        # "buy" | "sell"
    order_type: str = "limit"   # "limit" | "market" | "post_only" | "fok" | "ioc"
    price: float    = 0.0       # original limit price (0 for market orders)
    quantity: float = 0.0       # original order quantity

    # ── Lifecycle state ───────────────────────────────────────────────────
    state: str = OrderState.PENDING_SUBMIT  # see OrderState constants

    # ── Cumulative fill tracking ──────────────────────────────────────────
    filled_qty:     float = 0.0   # accFillSz — running total filled quantity
    avg_fill_price: float = 0.0   # avgPx     — VWAP of all fills so far

    # ── Per-fill info (populated only when fill_id is non-empty) ──────────
    fill_id:      str   = ""    # fillId / tradeId — unique per execution
    fill_price:   float = 0.0   # execution price of this fill
    fill_qty:     float = 0.0   # quantity executed in this fill
    fill_fee:     float = 0.0   # fee for this fill (negative = cost, positive = rebate)
    fill_fee_ccy: str   = ""    # fee currency e.g. "USDT", "BTC"
    fill_pnl:     float = 0.0   # realised PnL from this fill (reduce-only legs)
    fill_time_ms: int   = 0     # fill timestamp in milliseconds

    # ── Timestamps ────────────────────────────────────────────────────────
    create_time_ms: int = 0     # order creation time (exchange cTime)
    update_time_ms: int = 0     # last state change time (exchange uTime)

    # ── Metadata ──────────────────────────────────────────────────────────
    update_source: str = "ws"   # "ws" | "rest" | "risk" — origin of this update
    reject_reason: str = ""     # populated when state == REJECTED

    # ── Derived helpers ───────────────────────────────────────────────────
    @property
    def is_fill(self) -> bool:
        """True when this update carries an individual fill event."""
        return bool(self.fill_id)

    @property
    def is_terminal(self) -> bool:
        """True when no further updates are expected for this order."""
        return self.state in OrderState.TERMINAL

    @property
    def remaining_qty(self) -> float:
        return max(0.0, self.quantity - self.filled_qty)

    def to_redis_dict(self) -> dict:
        """Flat string dict suitable for Redis XADD / HSET."""
        return {k: str(v) for k, v in asdict(self).items()}

    @classmethod
    def from_redis_dict(cls, d: dict) -> "OrderUpdate":
        """Reconstruct from a flat Redis dict (all values are strings)."""
        def _coerce(key: str, val: str):
            float_fields = {
                "price", "quantity", "filled_qty", "avg_fill_price",
                "fill_price", "fill_qty", "fill_fee", "fill_pnl",
            }
            int_fields = {"fill_time_ms", "create_time_ms", "update_time_ms"}
            if key in float_fields:
                return float(val or 0)
            if key in int_fields:
                return int(val or 0)
            return val
        return cls(**{k: _coerce(k, v) for k, v in d.items()
                      if k in cls.__dataclass_fields__})


