@dataclass
class SymbolPosition:
    """
    Single-symbol position tracker using VWAP cost basis.

    PnL accounting
    ──────────────
    realized_pnl   Gross PnL from closed portions, minus fees already deducted.
    unrealized_pnl Mark-to-market on the open position:
                       (last_price − avg_entry) × net_qty
    total_pnl      realized_pnl + unrealized_pnl
    total_fees     Running sum of all fees paid (already deducted from realized_pnl).

    Delta
    ─────
    net_qty        Signed quantity: positive = long, negative = short.
    dollar_delta   net_qty × last_price  (uses avg_entry as fallback before first tick).
    """

    symbol: str
    gateway: str = ""
    strategy: str = ""

    # ── Position state ──────────────────────────────────────────────────────
    net_qty: float         = 0.0   # positive = long, negative = short
    avg_entry_price: float = 0.0   # VWAP of the current open position

    # ── PnL ─────────────────────────────────────────────────────────────────
    realized_pnl: float = 0.0     # net of fees, from fully/partially closed lots
    total_fees: float   = 0.0     # cumulative fees paid (informational only)

    # ── Mark to market ───────────────────────────────────────────────────────
    last_price: float   = 0.0
    last_update_ms: int = 0

    # ── Derived properties ───────────────────────────────────────────────────

    @property
    def unrealized_pnl(self) -> float:
        if self.net_qty == 0 or self.last_price == 0 or self.avg_entry_price == 0:
            return 0.0
        return (self.last_price - self.avg_entry_price) * self.net_qty

    @property
    def dollar_delta(self) -> float:
        """Net USD-equivalent directional exposure."""
        mark = self.last_price or self.avg_entry_price
        return self.net_qty * mark

    @property
    def total_pnl(self) -> float:
        return self.realized_pnl + self.unrealized_pnl

    # ── Fill application ─────────────────────────────────────────────────────

    def apply_fill(self, side: str, fill_qty: float, fill_price: float,
                   fee: float = 0.0) -> None:
        """
        Update position on a new fill.

        VWAP rules
        ──────────
        Adding to position   → update avg_entry_price (VWAP blend)
        Reducing position    → realise PnL on closed qty; avg_entry unchanged
        Crossing zero (flip) → realise PnL on old position; new position
                               opens at fill_price
        """
        if fill_qty <= 0 or fill_price <= 0:
            return

        signed  = fill_qty if side == "buy" else -fill_qty
        old_qty = self.net_qty
        new_qty = old_qty + signed

        if old_qty == 0:
            # Opening from flat
            self.avg_entry_price = fill_price

        elif (old_qty > 0) == (signed > 0):
            # Adding in same direction: VWAP blend
            total_abs = abs(old_qty) + fill_qty
            self.avg_entry_price = (
                abs(old_qty) * self.avg_entry_price + fill_qty * fill_price
            ) / total_abs

        else:
            # Reducing or crossing zero
            close_qty = min(abs(old_qty), fill_qty)

            if old_qty > 0:
                # Closing long: profit when fill_price > avg_entry
                self.realized_pnl += (fill_price - self.avg_entry_price) * close_qty
            else:
                # Closing short: profit when fill_price < avg_entry
                self.realized_pnl += (self.avg_entry_price - fill_price) * close_qty

            if new_qty != 0 and ((old_qty > 0) != (new_qty > 0)):
                # Crossed zero: new position opens at this fill_price
                self.avg_entry_price = fill_price
            elif new_qty == 0:
                self.avg_entry_price = 0.0
            # else: partial close — avg_entry unchanged for remaining qty

        self.net_qty = new_qty

        # Fees reduce realized PnL; tracked separately for reporting
        self.realized_pnl -= abs(fee)
        self.total_fees   += abs(fee)
        self.last_update_ms = int(time.time() * 1000)

    # ── Serialisation ────────────────────────────────────────────────────────

    def to_dict(self) -> dict:
        return {
            "symbol":          self.symbol,
            "gateway":         self.gateway,
            "strategy":        self.strategy,
            "net_qty":         self.net_qty,
            "avg_entry_price": round(self.avg_entry_price, 8),
            "realized_pnl":    round(self.realized_pnl, 8),
            "unrealized_pnl":  round(self.unrealized_pnl, 8),
            "total_pnl":       round(self.total_pnl, 8),
            "total_fees":      round(self.total_fees, 8),
            "dollar_delta":    round(self.dollar_delta, 2),
            "last_price":      self.last_price,
            "last_update_ms":  self.last_update_ms,
        }
